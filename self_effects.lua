-- The avatar's flag words (the state bits from the optional signature), for the log.
local function flags_text(a)
    local at = a.avatars + a.index * V.avatar_stride
    return 'flags ' .. hex64(read(at + V.flags, 8)) .. ', state bits '
           .. (V.state_bits and hex64(read(at + V.state_bits, 8)) or 'unknown')
end

-- The ragdoll flag, read from memory (true, false, or nil if unreadable).
local function ragdoll_flag(a)
    local high = read32(a.avatars + a.index * V.avatar_stride + V.flags + 4)
    if not high then return nil end
    return bit.band(bit.rshift(high, RAGDOLL_BIT - 32), 1) == 1
end

local function ragdoll(a)
    if fn.is_ragdolled(a.state) ~= 0 then note('Ragdoll: already ragdolled'); return end
    if fn.can_ragdoll(a.state) == 0 then note('Ragdoll: not allowed right now (' .. flags_text(a) .. ')'); return end
    note(string.format('Ragdoll: starting (entity %d, avatar %d, %s)', a.entity, a.index, flags_text(a)))
    fn.start_ragdoll(a.state, 0)
    local now = fn.is_ragdolled(a.state) ~= 0
    note(now and 'Ragdolled' or 'Started, but not ragdolled (' .. flags_text(a) .. ')')
    if not now then return end
    watch(a.entity, function(b, age)
        local still = ragdoll_flag(b)
        if still and age < WATCH.ragdoll then return false end
        note(string.format('Ragdoll %s after %.1f s', still and 'still on, no longer watched' or 'ended', age))
        return true
    end)
end


-- The local Helldiver

-- Low 32 bits of a * b (both 32-bit), exact in doubles.
local function mul32(a, b)
    local al, ah, bl, bh = a % 65536, math.floor(a / 65536), b % 65536, math.floor(b / 65536)
    return (al * bl + ((ah * bl + al * bh) % 65536) * 65536) % 4294967296
end

-- The game's id hash maps: rows of (key, value) u32 pairs at data, capacity a power of two, probed linearly from
-- key * mult. Returns the value, or nil and a reason.
local function lookup(base, map, cap, empty, mult, key)
    local data = pointer(read(base + map, 8))
    local capacity, empty_key, multiplier = read32(base + cap), read32(base + empty), read32(base + mult)
    if not (data and capacity and empty_key and multiplier) then return nil, 'map unreadable' end
    if capacity == 0 then return nil, 'map empty' end
    if capacity > 16777216 or bit.band(capacity, capacity - 1) ~= 0 then return nil, 'map capacity unexpected' end
    local hash = mul32(key, multiplier)
    for probe = 0, math.min(capacity, MAX_PROBES) - 1 do
        local row = read(data + ((hash + probe) % capacity) * 8, 8)
        if not row then return nil, 'map row unreadable' end
        local k = u32(row, 0)
        if k == empty_key then return nil, 'not in map' end
        if k == key then return u32(row, 4) end
    end
    return nil, 'not in map'
end

-- The local Helldiver: {state (its ragdoll state), entity, unit, index, avatars}, or nil and the reason.
local function local_avatar()
    local base = native.base
    local players = pointer(read(base + V.players, 8))
    if not players then return nil, 'no players' end
    if read32(players + V.local_active) == 0 then return nil, 'no local player' end
    local unit = read32(players + V.local_unit)
    if not unit then return nil, 'local unit unreadable' end
    if unit == V.no_unit then return nil, 'no Helldiver (no unit)' end
    local owner = pointer(read(base + V.owner, 8))
    if not owner then return nil, 'no entity owner' end
    local index, why = lookup(owner, V.unit_map, V.unit_cap, V.unit_empty, V.unit_mult, unit)
    if not index then return nil, 'unit ' .. unit .. ': ' .. why end
    if index >= MAX_ENTITIES then return nil, 'entity index unexpected' end
    local entity = read32(owner + V.entity_ids * 8 + index * 24)
    if not entity then return nil, 'entity unreadable' end
    if entity == read32(base + V.no_entity) then return nil, 'no Helldiver (no entity)' end
    local avatars = pointer(read(base + V.avatars, 8))
    if not avatars then return nil, 'no avatar manager' end
    local ai
    ai, why = lookup(avatars, V.avatar_map, V.avatar_cap, V.avatar_empty, V.avatar_mult, entity)
    if not ai then return nil, 'no Helldiver (entity ' .. entity .. ' ' .. why .. ')' end
    if ai >= MAX_AVATARS then return nil, 'avatar index unexpected' end
    local state = avatars + V.ragdoll_state + ai * V.avatar_stride
    if read32(state + V.state_entity) ~= entity then return nil, 'ragdoll state names another entity' end
    return {state = state, entity = entity, unit = unit, index = ai, avatars = avatars}
end


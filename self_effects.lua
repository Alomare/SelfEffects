-- Injuries: the game's damage queue at a limb's actor (RESEARCH.md, "Injuries")

-- The Helldiver's health record: {unit, network, record (bytes), creditor (uint64), life, health}, or nil and why.
-- Its descriptor must name the same entity, have an engine unit (the handle the actor lookup takes: not the players
-- list's unit id), belong to this machine and have a network id.
local function health_state(a)
    local h = pointer(read(native.base + V.health, 8))
    if not h then return nil, 'no health manager' end
    local index, why = lookup(h, V.health_slots, V.health_cap, V.health_empty, V.health_mult, a.entity)
    if not index then return nil, 'not in the health map (' .. why .. ')' end
    if index >= MAX_RECORDS then return nil, 'health index unexpected' end
    local descriptors = pointer(read(h + V.health_descriptors, 8))
    local d = descriptors and pointer(read(descriptors + index * 8, 8))
    local desc = d and read(d, 24)
    if not desc then return nil, 'health descriptor unreadable' end
    if u32(desc, 8) ~= a.entity then return nil, 'the health descriptor names another entity' end
    local unit = u32(desc, 12)
    if unit == 0 or unit == 0xFFFFFFFF then return nil, 'the Helldiver has no engine unit' end
    if u32(desc, 20) % 2 ~= 1 then return nil, 'this machine does not own the Helldiver' end
    local network = u32(desc, 16)
    if network == 0 or network >= 0x7fff then return nil, 'the Helldiver has no network id' end
    local records = pointer(read(h + V.health_records, 8))
    local record = records and read(records + index * V.health_stride, RECORD.size)
    if not record then return nil, 'health record unreadable' end
    local creditor = ffi.new('uint64_t[1]')
    ffi.copy(creditor, record:sub(RECORD.creditor + 1, RECORD.creditor + 8), 8)
    return {unit = unit, network = network, record = record, creditor = creditor[0], life = u32(record, RECORD.life),
            health = i32(record, RECORD.health)}
end

local function zone_health(h, zone) return i32(h.record, RECORD.zones + 4 * zone) end
local function zone_state(h, zone)
    local word = u32(h.record, RECORD.zone_states + math.floor(zone / 16) * 4)
    return bit.band(bit.rshift(word, 2 * (zone % 16)), 3)
end

-- The engine's unit actor lookup, through game.dll's engine API table, when it is the function the mod knows.
local function actor_lookup()
    local api = pointer(read(native.base + V.unit_api, 8))
    local at = api and pointer(read(api + V.actor_slot, 8))
    if not at then return nil, 'the engine API table is unreadable' end
    if read(at, #ACTOR_LOOKUP_START) ~= ACTOR_LOOKUP_START then return nil, 'the engine actor lookup changed' end
    return ffi.cast('SelfEffectsActor', at)
end

local function apply_injury(e, a)
    if family.injury ~= true then note(e.id .. ': injuries unavailable (' .. tostring(family.injury) .. ')'); return end
    local limb = e.limb
    local h, why = health_state(a)
    if not h then note(e.id .. ': ' .. why); return end
    if h.life ~= 0 then note(string.format('%s: not while %s', e.id, h.life == 1 and 'downed' or 'dead')); return end
    local left = zone_health(h, limb.zone)
    if not left or left <= 0 then
        note(string.format('%s: %s already injured (zone health %s, state %d)', e.id, limb.name, tostring(left),
                           zone_state(h, limb.zone)))
        return
    end
    local find, bad = actor_lookup()
    if not find then note(e.id .. ': ' .. bad); return end
    local actor = tonumber(find(h.unit, limb.actor, nil))
    if actor == 0xFFFFFFFF then note(e.id .. ': the Helldiver has no ' .. limb.name .. ' actor now'); return end
    local before = queue_count(V.damage_count)
    if not before or before >= QUEUE_CAPACITY then
        note(e.id .. ': the damage queue is ' .. (before and 'full' or 'unreadable'))
        return
    end
    local damage = math.min(limb.full, left)
    -- The VG-70 Variable's self-damage template (kind 6, element 0; HD2Runtime's research): dealt by and owned by
    -- the Helldiver (its network id), the record's own last-hit creditor kept, at the limb's actor. The game copies
    -- both vectors during the call.
    local direction, position = ffi.new('float[3]', 0, 0, -1), ffi.new('float[3]', 0, 0, 0)
    fn.damage_request(nil, 6, 0, a.entity, damage, 1, h.network, h.network, h.creditor, 0, 0, 0, 0, direction,
                      position, actor, 9, 0, 1)
    local queued = queue_count(V.damage_count) == before + 1
    note(string.format('%s: %d damage at %s (unit %d, actor %d, zone %d health %d, Helldiver health %d, '
                       .. 'network id %d) %s', e.id, damage, limb.name, h.unit, actor, limb.zone, left,
                       h.health or -1, h.network, queued and 'requested' or 'not queued'))
    if not queued then return end
    watch(a.entity, function(b, age)
        local now = health_state(b)
        if not now then return false end
        local zone = zone_health(now, limb.zone)
        if zone == left and age < WATCH.injury then return false end
        note(string.format('%s: after %.1f s, zone %d health %d -> %d (state %d), Helldiver health %d -> %d', e.id,
                           age, limb.zone, left, zone or -1, zone_state(now, limb.zone), h.health or -1,
                           now.health or -1))
        return true
    end)
end


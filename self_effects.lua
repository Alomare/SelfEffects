-- Watches: effects we started, logged until they settle (reads only; the game ends every effect)

local watches = {}

local function watch(entity, step)
    watches[#watches + 1] = {entity = entity, since = M.time, step = step}
end

local function watch_step()
    if #watches == 0 or M.frames % WATCH_EVERY ~= 0 then return end
    local a = local_avatar()
    for i = #watches, 1, -1 do
        local w = watches[i]
        local age = M.time - w.since
        local done
        if not a or a.entity ~= w.entity then
            note(string.format('%s: Helldiver gone after %.1f s, no longer watched', w.label or 'Effect', age))
            done = true
        else
            local ok, finished = pcall(w.step, a, age)
            done = not ok or finished
            if not ok then note('Watch error: ' .. tostring(finished)) end
        end
        if done then table.remove(watches, i) end
    end
end


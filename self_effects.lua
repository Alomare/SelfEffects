local code = nil  -- the signature engine
local V = {}      -- values read from the matched code (offsets; globals and functions as rvas)
local fn = nil    -- the game's functions: is_ragdolled, can_ragdoll, start_ragdoll, status_request, damage_request
local family = {} -- family name -> true, or the reason its effects are unavailable

local function family_check(name)
    local f = FAMILIES[name]
    for _, sig in ipairs(f.signatures) do
        if not code.found[sig] then return 'code not found: ' .. sig .. ' (' .. tostring(code.missing[sig]) .. ')' end
    end
    for _, value in ipairs(f.values) do
        if V[value] == nil then return 'value missing: ' .. value end
    end
    if name == 'status' and V.call_susceptible == nil then return 'value missing: call_susceptible' end
    if (name == 'injury' or name == 'explode') and V.health_stride < RECORD.size then
        return 'health records smaller than expected'
    end
    return true
end

local function finish_resolution()
    V = code.values
    local missing = code:missing_list()
    local why = nil
    for _, name in ipairs(REQUIRED) do
        if not code.found[name] then why = 'code not found: ' .. table.concat(missing, ', ') end
    end
    if not why and #code.problems > 0 then why = table.concat(code.problems, ', ') end
    -- The functions the matched calls go to are the ones found by their own code.
    if not why and V.unit_entity ~= code.found.unit_lookup then why = 'the unit lookup differs from its call' end
    if not why and V.is_ragdolled ~= code.found.ragdoll_check then why = 'the ragdoll check differs from its call' end
    if not why then
        for _, name in ipairs({'players', 'local_active', 'local_unit', 'no_entity', 'avatars', 'avatar_cap',
                               'avatar_mult', 'avatar_map', 'avatar_empty', 'owner', 'no_unit', 'unit_cap',
                               'unit_mult', 'unit_map', 'unit_empty', 'entity_ids', 'avatar_stride',
                               'ragdoll_state', 'state_entity', 'flags', 'can_ragdoll', 'start_ragdoll'}) do
            if V[name] == nil then why = 'value missing: ' .. name; break end
        end
    end
    if why then
        note('Not available: ' .. why)
        write_status({'NOT AVAILABLE - ' .. why .. '; the game is unchanged', 'Self-Effects ' .. M.version})
        M.retired = true
        return
    end
    local base = native.base
    fn = {is_ragdolled = ffi.cast('SelfEffectsCheck', base + V.is_ragdolled),
          can_ragdoll = ffi.cast('SelfEffectsCheck', base + V.can_ragdoll),
          start_ragdoll = ffi.cast('SelfEffectsStart', base + V.start_ragdoll)}
    for _, name in ipairs(FAMILY_NAMES) do
        family[name] = family_check(name)
        note(string.format('Effects (%s): %s', name, family[name] == true and 'available' or family[name]))
    end
    if family.status == true then fn.status_request = ffi.cast('SelfEffectsStatus', base + code.found.status_request) end
    if family.injury == true or family.explode == true then fn.damage_request = ffi.cast('SelfEffectsDamage', base + code.found.damage_request) end
    if family.launch == true then fn.set_velocity = ffi.cast('SelfEffectsVelocity', base + code.found.velocity) end
    M.ready = true
    if #code.moved > 0 then note('Moved code found: ' .. table.concat(code.moved, ', ')) end
    if #missing > 0 then note('Optional code not found: ' .. table.concat(missing, ', ')) end
    note(string.format('Ready: avatar state = avatars + 0x%x + index * 0x%x, entity at +0x%x', V.ragdoll_state,
                       V.avatar_stride, V.state_entity))
end


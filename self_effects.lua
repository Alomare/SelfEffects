local function set_choice(i, value)
    local slot = SLOTS[i]
    value = math.floor(tonumber(value) or slot.default)
    if not slot.effects[value] then value = slot.default end
    if value ~= options.choice[i] then note(string.format('Effect %d set to %s', i, slot.effects[value])) end
    options.choice[i] = value
end

local function connect_options()
    local menu = rawget(_G, 'ModOptionsMenu')
    if type(menu) ~= 'table' or menu.api ~= 1 then return end
    options.menu = menu
    for i, slot in ipairs(SLOTS) do
        local choices = {}
        for k, id in ipairs(slot.effects) do
            if k > MAX_CHOICES then break end
            choices[k] = host_text(menu, 2, 'effect.' .. id, 48)
        end
        local ok, done, why = pcall(menu.register_option, slot.option, {
            type = 'choice', mod_id = OPTIONS_MOD, label = host_text(menu, 2, 'option.effect_' .. i, 64),
            mod = host_text(menu, 2, 'option.mod', 40), choices = choices, default = slot.default,
            description = host_text(menu, 2, 'option.effect.description', 400), gap = i == 1 or nil})
        if ok and done then
            pcall(menu.on_change, slot.option, function(value) set_choice(i, value) end)
            local got, value = pcall(menu.get, slot.option)
            set_choice(i, got and value)
        else
            note('Option ' .. slot.option .. ' not registered: ' .. tostring(ok and why or done))
        end
    end
    note('Mod Options Menu connected (version ' .. tostring(menu.version or 1) .. ')')
end


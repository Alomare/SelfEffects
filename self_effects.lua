-- Launch: the game's movement velocity setter (RESEARCH.md, "Launch")

-- The Helldiver's velocity {x, y, z} in its motion record, or nil and why. SetVelocity writes the record its own map
-- lookup gives without checking that it found one, so the mod looks the entity up first.
local function motion_velocity(entity)
    local m = pointer(read(native.base + V.motion, 8))
    if not m then return nil, 'no motion manager' end
    local index, why = lookup(m, V.motion_slots, V.motion_cap, V.motion_empty, V.motion_mult, entity)
    if not index then return nil, 'not in the motion map (' .. why .. ')' end
    if index >= MAX_MOTION then return nil, 'motion index unexpected' end
    local records = pointer(read(m + V.motion_records, 8))
    local v = records and vector(read(records + index * V.motion_stride, 12))
    if not v then return nil, 'the velocity is unreadable' end
    return v
end

local function apply_launch(e, a)
    if family.launch ~= true then note(e.id .. ': unavailable (' .. tostring(family.launch) .. ')'); return end
    local v, why = motion_velocity(a.entity)
    if not v then note(e.id .. ': ' .. why); return end
    local x, y, z = v[1] + e.push[1], v[2] + e.push[2], v[3] + e.push[3]
    local speed = math.sqrt(x * x + y * y + z * z)
    if speed > MAX_SPEED then
        note(string.format('%s: not now, the Helldiver would move at %.1f m/s', e.id, speed))
        return
    end
    -- The game copies the vector during the call.
    fn.set_velocity(nil, a.entity, ffi.new('float[3]', x, y, z))
    local now = motion_velocity(a.entity)
    note(string.format('%s: velocity (%.1f, %.1f, %.1f) -> (%.1f, %.1f, %.1f), read back %s', e.id, v[1], v[2], v[3],
                       x, y, z, now and string.format('(%.1f, %.1f, %.1f)', now[1], now[2], now[3]) or 'unreadable'))
    -- What the movement does with it: the vertical velocity over the next frames.
    local samples = {}
    watch(a.entity, function(b, age)
        local w = motion_velocity(b.entity)
        samples[#samples + 1] = w and string.format('%.1f', w[3]) or '?'
        if age < WATCH.launch then return false end
        note(string.format('%s: vertical velocity every %d frames: %s', e.id, WATCH_EVERY, table.concat(samples, ' ')))
        return true
    end)
end


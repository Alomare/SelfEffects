-- Self-Effects by Alomare (formerly Ragdoll On Command).
--
-- Bad things on your own Helldiver at a key press. Three Mod Bindings Menu keys (Options > Controls > MODS: Effect 1
-- to 3, unbound at first; Effect 1 keeps the key Ragdoll On Command's Ragdoll binding had), each set to one effect in
-- Mod Options Menu (escape menu > MODS; without it the keys are Ragdoll, Rooted and Stun). Every effect is the game's
-- own, on the local Helldiver only:
--   - the ragdoll: the knockdown's sequence (not already ragdolled, allowed right now, start); the game stands the
--     Helldiver up by itself, as after an explosion;
--   - statuses (fire, stun, gas, bleeding...): the game's status request queue, with the Helldiver as target and
--     instigator and the buildup the game's own requests use; the game checks that the Helldiver can have the status

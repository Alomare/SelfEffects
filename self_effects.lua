local native = {}

local function init_native()
    -- Every mod shares one FFI namespace, and a name declared first keeps its declaration (a later ffi.cdef of it
    -- fails): the Windows functions are declared under this mod's own names (asm aliases of the real exports), so
    -- another mod's declarations of the bare names, with other types, can't change these calls.
    for _, decl in ipairs({
        'void *self_effects_GetCurrentProcess(void) __asm__("GetCurrentProcess");',
        'void *self_effects_GetModuleHandleA(const char *name) __asm__("GetModuleHandleA");',
        'int self_effects_ReadProcessMemory(void *process, const void *address, void *buffer, size_t size, '
            .. 'size_t *read) __asm__("ReadProcessMemory");',
    }) do pcall(ffi.cdef, decl) end
    -- The game's functions, declared once by name (a function pointer type string adds a C type on every use).
    for name, decl in pairs({
        SelfEffectsCheck = 'typedef uint8_t (*SelfEffectsCheck)(uint64_t state);',
        SelfEffectsStart = 'typedef void (*SelfEffectsStart)(uint64_t state, uint64_t mode);',
        -- QueueStatusRequest(ignored, type, target, buildup, instigator, variant)
        SelfEffectsStatus = 'typedef void (*SelfEffectsStatus)(void *ignored, uint32_t type, uint32_t target, '
            .. 'float buildup, uint32_t instigator, uint32_t variant);',
        -- QueueDamage(ignored, kind, element, target, damage, a6, dealer, owner, creditor, a10, f11, f12, f13,
        -- direction, position, actor, a17, a18, f19) (HD2Runtime's research)
        SelfEffectsDamage = 'typedef void (*SelfEffectsDamage)(void *ignored, uint32_t kind, uint32_t element, '
            .. 'uint32_t target, uint32_t damage, uint8_t a6, uint32_t dealer, uint32_t owner, uint64_t creditor, '
            .. 'uint32_t a10, float f11, float f12, float f13, const float *direction, const float *position, '
            .. 'uint32_t actor, uint32_t a17, uint32_t a18, float f19);',
        -- The engine's unit actor lookup(unit, actor name, null) -> actor handle (0xFFFFFFFF: none)
        SelfEffectsActor = 'typedef uint32_t (*SelfEffectsActor)(uint32_t unit, uint32_t name, uint32_t *out);',
        -- SetVelocity(ignored, entity, v)
        SelfEffectsVelocity = 'typedef void (*SelfEffectsVelocity)(void *ignored, uint32_t entity, const float *v);',
    }) do
        if not pcall(ffi.typeof, name) then ffi.cdef(decl) end
    end
    local ok, k32 = pcall(ffi.load, 'kernel32')
    if not ok then return false, 'kernel32 unavailable' end
    native.k32, native.process = k32, k32.self_effects_GetCurrentProcess()
    local game = k32.self_effects_GetModuleHandleA('game.dll')
    if game == nil then return false, 'game.dll not loaded' end
    native.base = tonumber(ffi.cast('uint64_t', game))
    return true
end

local function read(address, size)
    local buf, got = ffi.new('uint8_t[?]', size), ffi.new('size_t[1]')
    if native.k32.self_effects_ReadProcessMemory(native.process, ffi.cast('const void *', address), buf, size, got) == 0
       or tonumber(got[0]) ~= size then
        return nil
    end
    return ffi.string(buf, size)
end

local function u32(blob, offset)
    offset = offset or 0
    if not blob or #blob < offset + 4 then return nil end
    local v = ffi.new('uint32_t[1]')
    ffi.copy(v, blob:sub(offset + 1, offset + 4), 4)
    return tonumber(v[0])
end

local function i32(blob, offset)
    local v = u32(blob, offset)
    return v and (v >= 2147483648 and v - 4294967296 or v)
end

local function read32(address) return u32(read(address, 4)) end

local function pointer(blob)
    if not blob or #blob ~= 8 then return nil end
    local v = ffi.new('uint64_t[1]')
    ffi.copy(v, blob, 8)
    local a = tonumber(v[0])
    if a < 0x10000 or a >= 0x800000000000 then return nil end
    return a
end

-- Three floats {x, y, z}, or nil when unreadable or not finite and in range.
local function vector(blob)
    if not blob or #blob ~= 12 then return nil end
    local v = ffi.new('float[3]')
    ffi.copy(v, blob, 12)
    local out = {v[0], v[1], v[2]}
    for _, c in ipairs(out) do
        if c ~= c or math.abs(c) > 100000 then return nil end
    end
    return out
end

-- The code at an address against a pattern (hex bytes, '??' = any byte).
local function code_matches(at, pattern)
    local want = {}
    for b in pattern:gmatch('%S+') do want[#want + 1] = b ~= '??' and tonumber(b, 16) end
    local got = read(at, #want)
    if not got then return false end
    for k = 1, #want do
        if want[k] and got:byte(k) ~= want[k] then return false end
    end
    return true
end

local function hex64(blob)
    if not blob or #blob ~= 8 then return 'unreadable' end
    return string.format('%08x%08x', u32(blob, 4), u32(blob, 0))
end


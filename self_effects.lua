local status_rows = {}  -- type -> true once its settings row was checked

-- The settings row of a status type: it must hold the type, and the name it stores must be the catalogued one
-- (an unreadable name is logged and accepted). true, or nil and why.
local function status_row(ty, name)
    if status_rows[ty] then return true end
    local row = pointer(read(native.base + V.status_settings + ty * 8, 8))
    if not row then return nil, 'settings row unreadable' end
    local held = read32(row)
    if held ~= ty then return nil, 'settings row holds type ' .. tostring(held) end
    local text = pointer(read(row + 8, 8))
    local got = text and read(text, #name + 1)
    if got and got ~= name .. '\0' then
        return nil, 'settings row named "' .. ((read(text, 32) or ''):match('^[%w %-_]*')) .. '"'
    end
    note(string.format('Status %d (%s): settings row checked%s', ty, name, got and '' or ' (its name unreadable)'))
    status_rows[ty] = true
    return true
end

-- The entity's status zone masks (STATUS_ZONES x 16 bytes; bit = type), or nil and why.
local function status_masks(entity)
    local m = pointer(read(native.base + V.status, 8))
    if not m then return nil, 'no status manager' end
    local index, why = lookup(m, V.status_slots, V.status_cap, V.status_empty, V.status_mult, entity)
    if not index then return nil, why end
    if index == 0xFFFFFFFF then return nil, 'no status block' end
    local blocks = pointer(read(m + V.status_blocks, 8))
    local masks = blocks and read(blocks + index * V.status_stride, STATUS_ZONES * 16)
    if not masks then return nil, 'status block unreadable' end
    return masks
end

local function has_status(masks, ty)
    if not masks then return false end
    local byte, b = math.floor(ty / 8), ty % 8
    for z = 0, STATUS_ZONES - 1 do
        if bit.band(masks:byte(z * 16 + byte + 1) or 0, bit.lshift(1, b)) ~= 0 then return true end
    end
    return false
end

local function queue_count(offset)
    local queues = pointer(read(native.base + V.queues, 8))
    return queues and read32(queues + offset)
end

local function apply_status(e, a)
    if family.status ~= true then note(e.id .. ': statuses unavailable (' .. tostring(family.status) .. ')'); return end
    local masks, why = status_masks(a.entity)
    if not masks then note(e.id .. ': the Helldiver has no status block now (' .. tostring(why) .. ')'); return end
    local asked = {}
    for _, s in ipairs(e.statuses) do
        local ty, name = s[1], s[2]
        local ok, bad = status_row(ty, name)
        local before = ok and queue_count(V.status_count)
        if not ok then
            note(string.format('%s: status %d not requested: %s', e.id, ty, bad))
        elseif not before or before >= QUEUE_CAPACITY then
            note(string.format('%s: status %d not requested: the queue is %s', e.id, ty, before and 'full' or 'unreadable'))
        else
            local on = has_status(masks, ty)
            fn.status_request(nil, ty, a.entity, BUILDUP, a.entity, 0)
            local queued = queue_count(V.status_count) == before + 1
            note(string.format('%s: status %d (%s) %s (it was %s)', e.id, ty, name,
                               queued and 'requested' or 'refused by the game (the Helldiver cannot have it now)',
                               on and 'on' or 'off'))
            if queued then asked[#asked + 1] = {ty = ty, name = name, was = on} end
        end
    end
    if #asked == 0 then return end
    -- When each status shows in the Helldiver's masks and when it ends.
    watch(a.entity, function(b, age)
        local now = status_masks(b.entity)
        local open = false
        for _, s in ipairs(asked) do
            local on = has_status(now, s.ty)
            if on and not s.on_at then
                s.on_at = age
                note(string.format('%s: %s on after %.1f s', e.id, s.name, age))
            elseif not on and s.on_at and not s.off_at then
                s.off_at = age
                note(string.format('%s: %s ended after %.1f s (on for %.1f s)', e.id, s.name, age, age - s.on_at))
            elseif not s.on_at and not s.off_at and age >= WATCH.status_never then
                s.off_at = age
                note(string.format('%s: %s never showed in %.0f s', e.id, s.name, WATCH.status_never))
            end
            if not s.off_at then
                if age < WATCH.status then
                    open = true
                else
                    s.off_at = age
                    note(string.format('%s: %s still on after %.0f s, no longer watched', e.id, s.name, age))
                end
            end
        end
        return not open
    end)
end


-- Explode: a killing hit on the Helldiver alone, and a blast only this machine shows (RESEARCH.md, "Explode")

local registry_global = nil  -- the engine's unit registry global, once the code that reads it was checked
local blast_logged = {}      -- the blast's first engine calls, logged once each before they run

-- The engine's unit registry global, from the code of the world position function the ragdoll start calls; nil and
-- why when that code is not the code the mod knows.
local function unit_registry()
    if registry_global then return registry_global end
    local api = pointer(read(native.base + V.engine_api, 8))
    local functions = api and pointer(read(api + V.position_table, 8))
    local at = functions and pointer(read(functions + V.position_slot, 8))
    if not at then return nil, 'the engine API table is unreadable' end
    if not code_matches(at, POSITION_CODE) then return nil, 'the engine world position changed' end
    local object_at = at + 14 + i32(read(at + 10, 4))
    if not code_matches(object_at, UNIT_OBJECT_CODE) then return nil, 'the engine unit lookup changed' end
    registry_global = object_at + 22 + i32(read(object_at + 18, 4))
    return registry_global
end

-- An engine unit's root position {x, y, z}, read the way the engine's world position computes it; nil and why.
local function unit_position(unit)
    local global, why = unit_registry()
    if not global then return nil, why end
    local registry = pointer(read(global, 8))
    if not registry then return nil, 'no engine unit registry' end
    local index, generation = unit % 0x400000, math.floor(unit / 0x400000) % 256
    local count = read32(registry + ENGINE.count)
    if not count or index >= count then return nil, 'the engine has no such unit' end
    local generations = pointer(read(registry + ENGINE.generations, 8))
    local current = generations and read(generations + index, 1)
    if not current or current:byte() ~= generation then return nil, 'the engine unit is gone' end
    local objects = pointer(read(registry + ENGINE.objects, 8))
    local object = objects and pointer(read(objects + index * 8, 8))
    if not object or read32(object + ENGINE.unit) ~= unit then return nil, 'the engine unit object names another unit' end
    local methods = pointer(read(object, 8))
    local graph = methods and pointer(read(methods + ENGINE.graph_method, 8))
    if not graph or not code_matches(graph, SCENE_GRAPH_CODE) then return nil, 'the unit scene graph is unexpected' end
    local poses = pointer(read(object + ENGINE.graph + ENGINE.poses, 8))
    local position = poses and vector(read(poses + ENGINE.translation, 12))
    if not position then return nil, 'the unit position is unreadable' end
    return position
end

local function in_mission()
    local game = pointer(read(native.base + V.game, 8))
    return game ~= nil and read32(game + V.game_state) == GAME_MISSION
end

-- The world the local Helldiver is in, for the blast's particles and sound: the world with a Helldiver unit at the
-- position read from memory (the ship keeps one too, in another world). nil when none matches.
local function helldiver_world(S, at)
    local worlds = S.Application.worlds()
    for _, world in pairs(worlds) do
        -- A resource name made fresh for every use: IdString64 values are frame temporaries.
        local units = S.World.units_by_resource(world, S.IdString64.from_hex(HELLDIVER_RESOURCE))
        for _, unit in pairs(units or {}) do
            if S.Unit.alive(unit) then
                local p = S.Unit.world_position(unit, 1)
                local dx, dy, dz = p.x - at[1], p.y - at[2], p.z - at[3]
                if dx * dx + dy * dy + dz * dz <= WORLD_MATCH * WORLD_MATCH then return world end
            end
        end
    end
end

-- The blast this machine shows: an explosion's particles and sound at the Helldiver's feet, through the engine's
-- Lua API. Nothing in it damages or pushes anything. Each step only after its resource is known to be loaded (a
-- missing resource is an engine assert, which crashes the game). Returns what was shown, for the log.
local function show_blast(e, at)
    local S = rawget(_G, 'stingray')
    if type(S) ~= 'table' then return 'no engine API' end
    local world = helldiver_world(S, at)
    if not world then return 'no world with the Helldiver at that position' end
    local shown = {}
    local position = S.Vector3(at[1], at[2], at[3])
    if S.Application.can_get('particles', S.IdString64.from_hex(e.blast.particles)) then
        if not blast_logged.particles then blast_logged.particles = true; note(e.id .. ': first particles call') end
        local ok, err = pcall(S.World.create_particles, world, S.IdString64.from_hex(e.blast.particles), position,
                              S.Quaternion.identity())
        shown[#shown + 1] = ok and 'particles' or ('particles failed: ' .. tostring(err))
    else
        shown[#shown + 1] = 'particles not loaded'
    end
    local wwise, ww = S.Wwise, S.WwiseWorld
    if type(wwise) == 'table' and type(ww) == 'table' and wwise.has_event(e.blast.sound) then
        if not blast_logged.sound then blast_logged.sound = true; note(e.id .. ': first sound call') end
        local ok, err = pcall(function() ww.trigger_event(wwise.wwise_world(world), e.blast.sound, position) end)
        shown[#shown + 1] = ok and 'sound' or ('sound failed: ' .. tostring(err))
    else
        shown[#shown + 1] = 'sound not loaded'
    end
    return table.concat(shown, ', ')
end

-- Explode: this machine shows a blast at the Helldiver's feet, and the game's damage queue gets one hit on the
-- Helldiver alone, big enough to kill it, at no actor: the game then severs every gore group of the Helldiver (head,
-- arms, lower legs, hips) and tells the other machines, as for any death that tears a Helldiver apart. No explosion
-- is requested: nothing and nobody else is hit or pushed (RESEARCH.md, "Explode").
local function apply_explode(e, a)
    if family.explode ~= true then note(e.id .. ': unavailable (' .. tostring(family.explode) .. ')'); return end
    if not in_mission() then note(e.id .. ': only in a mission'); return end
    local h, why = health_state(a)
    if not h then note(e.id .. ': ' .. why); return end
    if h.life ~= 0 and h.life ~= 1 then note(e.id .. ': not while dead'); return end
    local at
    at, why = unit_position(h.unit)
    if not at then note(e.id .. ': ' .. why); return end
    local before = queue_count(V.damage_count)
    if not before or before >= QUEUE_CAPACITY then
        note(e.id .. ': the damage queue is ' .. (before and 'full' or 'unreadable'))
        return
    end
    -- The injury's template with no actor (0xFFFFFFFF: the drain then matches no damage zone, so main health takes
    -- the whole hit and the gore check runs every group), the push the severed parts get, upward.
    local direction, position = ffi.new('float[3]', 0, 0, 1), ffi.new('float[3]', at[1], at[2], at[3])
    fn.damage_request(nil, 6, 0, a.entity, e.damage, 1, h.network, h.network, h.creditor, 0, e.push, 0, 0, direction,
                      position, 0xFFFFFFFF, 9, 0, 1)
    local queued = queue_count(V.damage_count) == before + 1
    note(string.format('%s: %d damage at no actor (Helldiver health %d, life state %d) %s', e.id, e.damage,
                       h.health or -1, h.life or -1, queued and 'requested' or 'not queued'))
    if not queued then return end
    local ok, shown = pcall(show_blast, e, at)
    note(string.format('%s: blast at (%.1f, %.1f, %.1f): %s', e.id, at[1], at[2], at[3],
                       ok and shown or ('error: ' .. tostring(shown))))
    watch(a.entity, function(b, age)
        local now = health_state(b)
        if age < WATCH.explode and (not now or (now.health == h.health and now.life == h.life)) then return false end
        note(string.format('%s: after %.1f s, Helldiver health %d -> %s, life state %d -> %s', e.id, age,
                           h.health or -1, now and tostring(now.health) or '?', h.life or -1,
                           now and tostring(now.life) or '?'))
        return true
    end)
end

